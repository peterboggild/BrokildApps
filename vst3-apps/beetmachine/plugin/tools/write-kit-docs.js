// Writes every list of Beetmachine's kits - the manual's kit pages, the landing
// page's kit cards, the README line and the app.json counts - FROM the kit table
// in src/BeetKits.cpp. A list typed by hand beside the table it describes goes
// stale the day a kit is added; this one cannot.
//   node tools/write-kit-docs.js            (idempotent: run it after any kit edit)
const fs = require('fs');
const path = require('path');
const PLUG = path.join(__dirname, '..');
const APP = path.join(PLUG, '..');

// ---- parse the kit table ------------------------------------------------------------
const src = fs.readFileSync(path.join(PLUG, 'src/BeetKits.cpp'), 'utf8');
const body = src.slice(src.indexOf('static const Kit KITS[]'), src.indexOf('int numKits()'));
const kits = [];
const kitRe = /\{\s*"([^"]+)",\s*\{((?:\s*\{[^{}]*\},?)+)\s*\}\s*(?:,\s*R"\((.*?)\)")?\s*\}/gs;
let m;
while ((m = kitRe.exec(body)) !== null) {
  const slots = [...m[2].matchAll(/\{\s*(KICK|SNARE|HATS|EMPTY),\s*"([^"]*)",\s*([-0-9.f]+),\s*([-0-9.f]+),\s*([A-Z0-9|]+)(?:,\s*"([^"]*)")?\s*\}/g)]
    .map(s => ({ type: s[1], preset: s[2], choke: s[5], tweaks: s[6] || '' }));
  if (slots.length !== 8) throw new Error('kit ' + m[1] + ': ' + slots.length + ' slots parsed');
  kits.push({ name: m[1], slots, rack: m[3] ? JSON.parse(m[3]) : null });
}
if (kits.length < 10) throw new Error('only ' + kits.length + ' kits parsed');

const MOD = { saturation: 'TUBE', lofi: 'GRIT', strip: 'STRIP', delay: 'ECHO', reverb: 'SPACE', chorus: 'ENSEMBLE',
              phaser: 'SWEEP', shimmer: 'SHIMMER', trem: 'HARMONIC', stutter: 'GATE', rotary: 'ROTARY', kieranator: 'KIERANATOR' };
const SPACE = ['room', 'hall', 'plate', 'spring', 'reverse'];
function rackText(k) {
  if (!k.rack) return '';
  return Object.entries(k.rack.modules).map(([id, v]) => {
    let t = MOD[id] || id.toUpperCase();
    if (id === 'reverb' && v.p && v.p.character !== undefined) t += ' ' + SPACE[v.p.character].toUpperCase();
    return t;
  }).join(' + ');
}
const words = ['zero','one','two','three','four','five','six','seven','eight','nine','ten','eleven','twelve','thirteen',
  'fourteen','fifteen','sixteen','seventeen','eighteen','nineteen','twenty','twenty-one','twenty-two','twenty-three','twenty-four',
  'twenty-five','twenty-six','twenty-seven','twenty-eight','twenty-nine','thirty'];
const N = kits.length, NW = words[N], NWc = NW[0].toUpperCase() + NW.slice(1);
const nRack = kits.filter(k => k.rack).length;
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
console.log(N + ' kits, ' + nRack + ' with a rack');

const edits = [];
function edit(file, fn) { const p = path.join(APP, file); const s = fs.readFileSync(p, 'utf8'); const t = fn(s); edits.push([p, s, t]); }
function between(s, a, b, repl, file) {
  const i = s.indexOf(a), j = s.indexOf(b, i + a.length);
  if (i < 0 || j < 0) throw new Error(file + ': anchors not found: ' + a.slice(0, 50) + ' / ' + b.slice(0, 50));
  return s.slice(0, i) + repl + s.slice(j);
}
function once(s, a, b, file) {
  const c = s.split(a).length - 1;
  if (c !== 1) throw new Error(file + ': "' + a.slice(0, 60) + '" found ' + c + 'x');
  return s.split(a).join(b);
}
function onceOrDone(s, a, b, file) { return s.indexOf(b) >= 0 && s.indexOf(a) < 0 ? s : once(s, a, b, file); }

