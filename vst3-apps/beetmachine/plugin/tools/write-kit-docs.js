// ---- README and app.json -------------------------------------------------------------------------
edit('README.txt', s => {
  const names = kits.map(k => k.name).join(', ') + '.';
  const lines = []; let cur = '';
  for (const w of (names + ' A kit sets the sounds and the BWFX rack, never your notes or routing.').split(' ')) {
    if ((cur + ' ' + w).trim().length > 62) { lines.push(cur.trim()); cur = w; } else cur += ' ' + w;
  }
  lines.push(cur.trim());
  const block = 'KITS      ' + lines.join('\n          ') + '\n';
  return s.replace(/KITS      [\s\S]*?\n(?=BWFX      )/, block);
});
edit('app.json', s => s
  .replace(/Ten themed kits, from STUDIO and 808 to DUB, INDUSTRIAL and LO-FI\./,
           NWc + ' themed kits, from STUDIO and 808 to DUB SPACE, DNB, DOOM, BLACK METAL and HARD TECHNO, many with their own BWFX rack.')
  .replace(/[a-zA-Z0-9-]+ themed kits, from STUDIO[^"]*?BWFX rack\./,
           NWc + ' themed kits, from STUDIO and 808 to DUB SPACE, DNB, DOOM, BLACK METAL and HARD TECHNO, many with their own BWFX rack.')
  .replace(/· \d+ kits ·/, '· ' + N + ' kits ·'));

for (const [p, a, b] of edits) {
  if (a === b) { console.log('unchanged ' + path.relative(APP, p)); continue; }
  fs.writeFileSync(p, b); console.log('wrote ' + path.relative(APP, p));
}
