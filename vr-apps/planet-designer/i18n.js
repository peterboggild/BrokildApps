const TABLES = { da: DA, en: { ...DA, ...EN } };
let lang = 'da';
export function setLang(l) { lang = TABLES[l] ? l : 'da'; document.documentElement.lang = lang; }
export function getLang() { return lang; }
export function fmt(x, digits = 2) {
  if (typeof x !== 'number' || !isFinite(x)) return '–';
  const a = Math.abs(x);
  let opts;
  if (a !== 0 && (a < 0.001 || a >= 1e6)) return x.toExponential(1).replace('.', lang === 'da' ? ',' : '.');
  if (a >= 100) opts = { maximumFractionDigits: 0 };
  else if (a >= 10) opts = { maximumFractionDigits: Math.max(0, digits - 1) };
  else opts = { maximumSignificantDigits: Math.max(2, digits + 1) };
  return x.toLocaleString(lang === 'da' ? 'da-DK' : 'en-GB', opts);
}
/* HTML-escape: names come from the user and from share links, and texts are inserted as HTML. */
export const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
export function t(key, p) {
  let s = TABLES[lang][key];
  if (s === undefined) s = key;
  if (p) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in p ? (typeof p[k] === 'number' ? fmt(p[k]) : esc(p[k])) : m));
  return s;
}
