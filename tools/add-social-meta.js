#!/usr/bin/env node
/*
 * add-social-meta.js — give every public page a link preview.
 *
 * WHY THIS EXISTS
 *
 * The front page is data-driven: manifest.json lists the folders, each folder
 * carries its own app.json, and the cards are built by fetch() at runtime.
 * That is the right shape for the site and the wrong shape for a crawler.
 * Facebook, Discord, Slack, iMessage, WhatsApp and the rest do not run
 * JavaScript at all — they read the HTML as served and stop. So a Brokild link
 * pasted anywhere came out as a bare URL: no title, no image, no description,
 * for fifteen apps that each already had a finished 16:9 preview sitting in
 * assets/app-previews/.
 *
 * Open Graph tags have to be static in the served HTML, which is why this is a
 * generator that writes them into the files rather than anything at runtime.
 *
 * It invents no copy. Every tag is built from what the page and its app.json
 * already say — the <title>, the <meta name="description">, the app.json
 * preview. Run it again after editing either and the block is rewritten in
 * place; it is idempotent, so it is safe on every page, every time.
 *
 *   node tools/add-social-meta.js          # write
 *   node tools/add-social-meta.js --check  # exit 1 if anything is stale (CI)
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");

/* The published base. This repo has no CNAME file, and a Pages custom domain
 * requires one, so the site is served from the default project-pages URL.
 * If a custom domain is ever added, change this one line and re-run. */
const SITE = "https://peterboggild.github.io/BrokildApps";

const SITE_NAME = "BrokildApps";
const START = "<!-- social-meta:start — generated by tools/add-social-meta.js -->";
const END = "<!-- social-meta:end -->";

/* Pages that are not apps and carry no app.json of their own. */
const EXTRA = {
  "index.html": {
    image: "assets/app-previews/site-og.jpg",
    alt: "Panels from the Brokild plugins behind the word BROKILD",
    type: "website",
  },
  "dsw/index.html": {
    image: "assets/app-previews/site-og.jpg",
    alt: "Panels from the Brokild plugins behind the word BROKILD",
    type: "website",
  },
};

/* Redirect stubs and internal tools: a preview for a page whose only job is to
 * bounce you somewhere else is worse than none. */
const SKIP = new Set([
  "vst3-apps/mars-wars/index.html",
  "vst3-apps/photo-synth-2/index.html",
  "tools/video-sync/index.html",
]);

const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const exists = (p) => fs.existsSync(path.join(ROOT, p));

/* Decode the handful of entities the descriptions actually use, so the tag
 * carries the character rather than the escape, then re-encode for an
 * attribute. Everything here is already someone's prose — never reword it. */
function decode(s) {
  return s
    .replace(/&nbsp;/g, " ")
    .replace(/&mdash;/g, "—")
    .replace(/&ndash;/g, "–")
    .replace(/&hellip;/g, "…")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'");
}

function attr(s) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/* Most of these descriptions run 300–500 characters, which is right for the
 * page and long for an embed — Discord and Facebook cut mid-word and add an
 * ellipsis. Cut at the last sentence that ends before the limit instead, so
 * the embed shows whole sentences in his own words. Nothing is rewritten and
 * nothing is summarised: the tail is simply not shown. */
function clip(text, limit = 300) {
  const t = text.replace(/\s+/g, " ").trim();
  if (t.length <= limit) return t;
  const head = t.slice(0, limit);
  const cut = Math.max(head.lastIndexOf(". "), head.lastIndexOf("! "), head.lastIndexOf("? "));
  if (cut > limit * 0.45) return head.slice(0, cut + 1);
  const sp = head.lastIndexOf(" ");
  return (sp > 0 ? head.slice(0, sp) : head).replace(/[,;:—-]$/, "") + "…";
}

function tagOf(html, re) {
  const m = html.match(re);
  return m ? decode(m[1]).replace(/\s+/g, " ").trim() : null;
}

/* Build the page list: every app.json folder, plus the extras. */
function pages() {
  const out = [];
  const manifestApps = JSON.parse(read("manifest.json")).apps;
  const folders = new Set(manifestApps);

  /* Include folders that have an app.json even if the manifest has not caught
   * up with them — a page that exists and is linked deserves a preview. */
  for (const dir of ["vst3-apps", "music-apps", "health-apps"]) {
    for (const name of fs.readdirSync(path.join(ROOT, dir))) {
      const f = `${dir}/${name}`;
      if (exists(`${f}/app.json`)) folders.add(f);
    }
  }

  for (const folder of folders) {
    const app = JSON.parse(read(`${folder}/app.json`));
    const page = app.url || `${folder}/index.html`;
    if (SKIP.has(page) || !exists(page)) continue;
    let image = app.preview;
    /* Crawlers do not render SVG as a preview image. Where the card art is an
     * SVG there is a PNG of the same frame beside it for this purpose. */
    if (image && image.endsWith(".svg")) {
      const png = image.replace(/\.svg$/, ".png");
      if (exists(png)) image = png;
      else image = null;
    }
    out.push({
      page,
      image,
      alt: `${app.name} — panel preview`,
      type: "website",
      note: app.note || null,
    });
  }

  for (const [page, meta] of Object.entries(EXTRA)) {
    if (!exists(page)) continue;
    out.push({ page, ...meta, alt: meta.alt, note: null });
  }
  return out.sort((a, b) => a.page.localeCompare(b.page));
}

function blockFor(info) {
  const html = read(info.page);
  const title = tagOf(html, /<title>([\s\S]*?)<\/title>/i);
  const desc = tagOf(html, /<meta\s+name="description"\s+content="([\s\S]*?)"\s*\/?>/i);
  if (!title || !desc) throw new Error(`${info.page}: needs a <title> and a meta description`);

  /* og:site_name already says BrokildApps; repeating it in og:title just eats
   * embed width. */
  const ogTitle = title.replace(/\s*[|·]\s*BrokildApps\s*$/i, "").trim();
  const url = `${SITE}/${info.page}`.replace(/\/index\.html$/, "/");

  const lines = [
    START,
    `  <link rel="canonical" href="${attr(url)}" />`,
    `  <meta property="og:type" content="${info.type}" />`,
    `  <meta property="og:site_name" content="${SITE_NAME}" />`,
    `  <meta property="og:locale" content="en_GB" />`,
    `  <meta property="og:title" content="${attr(ogTitle)}" />`,
    `  <meta property="og:description" content="${attr(clip(desc))}" />`,
    `  <meta property="og:url" content="${attr(url)}" />`,
  ];

  if (info.image && exists(info.image)) {
    const abs = `${SITE}/${info.image}`;
    const dim = size(info.image);
    lines.push(`  <meta property="og:image" content="${attr(abs)}" />`);
    if (dim) {
      lines.push(`  <meta property="og:image:width" content="${dim.w}" />`);
      lines.push(`  <meta property="og:image:height" content="${dim.h}" />`);
    }
    lines.push(`  <meta property="og:image:alt" content="${attr(info.alt)}" />`);
    lines.push(`  <meta name="twitter:card" content="summary_large_image" />`);
    lines.push(`  <meta name="twitter:image" content="${attr(abs)}" />`);
  } else {
    lines.push(`  <meta name="twitter:card" content="summary" />`);
  }

  lines.push(`  <meta name="twitter:title" content="${attr(ogTitle)}" />`);
  lines.push(`  <meta name="twitter:description" content="${attr(clip(desc))}" />`);
  lines.push(END);
  return lines;
}

/* Dimensions straight out of the file header — og:image:width and :height let
 * a crawler lay the card out before it has fetched the image, and a wrong
 * number is worse than none. */
function size(rel) {
  const b = fs.readFileSync(path.join(ROOT, rel));
  if (b.slice(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])))
    return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
  if (b[0] === 0xff && b[1] === 0xd8) {
    let i = 2;
    while (i < b.length - 9) {
      if (b[i] !== 0xff) { i++; continue; }
      const m = b[i + 1];
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc)
        return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) };
      i += 2 + b.readUInt16BE(i + 2);
    }
  }
  return null;
}

/* The block sits directly under the description it is built from, and takes
 * that line's own indent — the landing pages indent their head by two spaces
 * and the two browser apps do not, so a hardcoded indent here rewrites those
 * two files on every run and the --check gate never settles. */
function apply(html, lines) {
  const anchor = html.match(/([ \t]*)<meta\s+name="description"[\s\S]*?>\n/i);
  if (!anchor) throw new Error("no meta description to anchor to");
  const indent = anchor[1];
  const block = lines.map((l) => indent + l).join("\n");

  const had = new RegExp(`[ \\t]*${START}[\\s\\S]*?${END}[ \\t]*\\n`);
  if (had.test(html)) return html.replace(had, `${block}\n`);
  return html.replace(anchor[0], `${anchor[0]}${block}\n`);
}

/* ------------------------------------------------------------------ *
 *  The front page's <noscript> list.
 *
 *  Same problem as the meta tags, one level down: the grid is built by
 *  fetch(), so with JavaScript off — or to anything that does not run it —
 *  <div id="appGrid"> is an empty box and the page offers no way to reach a
 *  single app. This writes the plain list of links that ought to be there,
 *  from manifest.json in manifest order, so the list cannot drift from the
 *  grid: adding an app to the manifest and re-running updates both.
 * ------------------------------------------------------------------ */
const NS_START = "<!-- noscript-apps:start — generated by tools/add-social-meta.js -->";
const NS_END = "<!-- noscript-apps:end -->";

function noscriptBlock() {
  const apps = JSON.parse(read("manifest.json")).apps;
  const items = [];
  for (const folder of apps) {
    if (!exists(`${folder}/app.json`)) continue;
    const app = JSON.parse(read(`${folder}/app.json`));
    const href = app.url || `${folder}/index.html`;
    if (!exists(href)) continue;
    items.push(
      `          <li><a href="${attr(href)}">${attr(app.name)}</a> — ` +
        `${attr(clip(decode(app.description), 180))}</li>`
    );
  }
  return [
    NS_START,
    `      <noscript>`,
    `        <p class="grid-state">The grid above is built in the browser. Here is the same list as plain links:</p>`,
    `        <ul class="noscript-apps">`,
    ...items,
    `        </ul>`,
    `      </noscript>`,
    NS_END,
  ];
}

function applyNoscript(html) {
  const lines = noscriptBlock();
  const indent = "      ";
  const block = lines.map((l, i) => (i === 0 || i === lines.length - 1 ? indent + l : l)).join("\n");
  const had = new RegExp(`[ \\t]*${NS_START}[\\s\\S]*?${NS_END}[ \\t]*\\n`);
  if (had.test(html)) return html.replace(had, `${block}\n`);
  const anchor = '      <div class="grid" id="appGrid" aria-live="polite"></div>\n';
  if (!html.includes(anchor)) throw new Error("index.html: no #appGrid to anchor the noscript list to");
  return html.replace(anchor, `${anchor}${block}\n`);
}

const check = process.argv.includes("--check");
let changed = 0;
for (const info of pages()) {
  const before = read(info.page);
  let after = apply(before, blockFor(info));
  if (info.page === "index.html") after = applyNoscript(after);
  const noImage = !(info.image && exists(info.image));
  if (after !== before) {
    changed++;
    if (!check) fs.writeFileSync(path.join(ROOT, info.page), after);
    console.log(`${check ? "STALE" : "wrote"}  ${info.page}${noImage ? "  (no preview image)" : ""}`);
  }
}
if (check && changed) {
  console.error(`\n${changed} page(s) have stale social meta — run: node tools/add-social-meta.js`);
  process.exit(1);
}
console.log(check ? "social meta up to date" : `${changed} page(s) updated`);
